// Generates src/data/airports.generated.ts from OpenFlights datasets.
// Run: node scripts/build-airports.mjs
// Inputs (download first):
//   /tmp/airports.dat  https://raw.githubusercontent.com/jpatokal/openflights/master/data/airports.dat
//   /tmp/routes.dat    https://raw.githubusercontent.com/jpatokal/openflights/master/data/routes.dat
import { readFileSync, writeFileSync } from "node:fs";

const AIRPORTS = "/tmp/airports.dat";
const ROUTES = "/tmp/routes.dat";
const OUT = "src/data/airports.generated.ts";

// Map OpenFlights country names → Swappup canonical names where they differ.
const COUNTRY_OVERRIDES = {
  "Burma": "Myanmar",
  "Cape Verde": "Cabo Verde",
  "Congo (Brazzaville)": "Republic of the Congo",
  "Congo (Kinshasa)": "Democratic Republic of the Congo",
  "Cote d'Ivoire": "Ivory Coast",
  "East Timor": "Timor-Leste",
  "Macedonia": "North Macedonia",
  "Palestine": "Palestinian Territories",
  "Russia": "Russian Federation",
  "South Korea": "South Korea",
  "Korea": "South Korea",
  "Swaziland": "Eswatini",
  "Syria": "Syrian Arab Republic",
  "Tanzania": "Tanzania",
  "Vatican City": "Holy See",
  "Virgin Islands": "U.S. Virgin Islands",
  "British Virgin Islands": "British Virgin Islands",
  "Czech Republic": "Czech Republic",
  "United States": "United States",
  "United Kingdom": "United Kingdom",
};

// Parse a CSV line that may contain quoted fields with commas.
function parseCsv(line) {
  const out = [];
  let cur = "";
  let inQ = false;
  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (ch === '"') { inQ = !inQ; continue; }
    if (ch === "," && !inQ) { out.push(cur); cur = ""; continue; }
    cur += ch;
  }
  out.push(cur);
  return out;
}

// Collect IATA codes that appear in routes.dat (proxy for "has commercial flights").
const activeIata = new Set();
for (const line of readFileSync(ROUTES, "utf8").split("\n")) {
  if (!line.trim()) continue;
  const f = parseCsv(line);
  const src = f[2];
  const dst = f[4];
  if (src && src.length === 3 && src !== "\\N") activeIata.add(src);
  if (dst && dst.length === 3 && dst !== "\\N") activeIata.add(dst);
}
console.log(`Active IATA codes in routes: ${activeIata.size}`);

const rows = [];
const unknownCountries = new Set();
for (const line of readFileSync(AIRPORTS, "utf8").split("\n")) {
  if (!line.trim()) continue;
  const f = parseCsv(line);
  // 0:id 1:name 2:city 3:country 4:iata 5:icao ... 12:type
  const name = f[1]?.trim();
  const city = f[2]?.trim();
  const rawCountry = f[3]?.trim();
  const iata = f[4]?.trim();
  const type = f[12]?.trim();
  if (!iata || iata === "\\N" || iata.length !== 3) continue;
  if (type && type !== "airport") continue;
  if (!activeIata.has(iata)) continue;
  if (!city || !rawCountry || !name) continue;
  const country = COUNTRY_OVERRIDES[rawCountry] ?? rawCountry;
  // Strip trailing "Airport"/"International Airport" noise for cleaner labels.
  let airportName = name
    .replace(/\s+International Airport$/i, "")
    .replace(/\s+Airport$/i, "")
    .trim();
  if (!airportName) airportName = name;
  rows.push({ city, country, airportCode: iata, airportName });
}

// Dedupe by IATA (some rows repeat between datasets).
const byIata = new Map();
for (const r of rows) byIata.set(r.airportCode, r);
const final = [...byIata.values()].sort((a, b) =>
  a.country.localeCompare(b.country) ||
  a.city.localeCompare(b.city) ||
  a.airportCode.localeCompare(b.airportCode),
);

console.log(`Output airports: ${final.length}`);
console.log(`Unique countries: ${new Set(final.map((r) => r.country)).size}`);
if (unknownCountries.size) console.log("Unmapped countries:", [...unknownCountries]);

const header = `// AUTO-GENERATED by scripts/build-airports.mjs from OpenFlights data.
// Do not edit by hand — re-run the generator to refresh.
import type { CityData } from "./flightData";

export const airports: CityData[] = `;

writeFileSync(OUT, header + JSON.stringify(final, null, 2) + ";\n");
console.log(`Wrote ${OUT}`);